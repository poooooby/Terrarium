"""Regenerate .modkitignore from rules, so the package list cannot drift.

    python tools/gen_modkitignore.py          # rewrite .modkitignore
    python tools/gen_modkitignore.py --check  # exit 1 if it is out of date

Why generated: gen1recomp's tools/modkit.py matches .modkitignore LITERALLY
-- one exact relative file path per line, no globs, no folders (it walks the
mod folder and drops a file only when its path is in the set). A folder entry
such as "tools/profiler/" matches nothing, and every new probe or tool needed
its own hand-written line. Here the rules are folders and patterns, and the
literal list is written out from `git ls-files`.

What ships is the mod a player loads -- main.lua, manifest.json, mod.card,
lib/, data/, assets/ -- plus the player docs (README, FEATURES, CHANGELOG) and
every LICENSE / CREDITS file. Everything below is development material.
"""
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

# whole folders that are never loaded by the game
FOLDERS = [
    "tests/",            # probes and offline tests, run by hand
    "tools/",            # authoring scripts, the profiler, vendored AppleCake
    "compat/",           # the Porygonal adapter is installed INTO Porygonal
    "concepts/",         # design boards
    "publish/",          # the original maintainer's store listing
    "publish-zip/",      # old packaged builds
    "assets/docs/",      # building catalogue and methodology notes
    "assets/ground/source/",   # contact sheets the ground strips were cut from
]

# single files at the root that are for developers, not players
FILES = [
    "CLAUDE.md",
    "ROADMAP.md",
    "MOBILE.md",
    "PARTICLES-PLAN.md",
    "PRECACHE-PLAN.md",
    "quiver-catalog-entry.json",
    "quiver-local-index.json",
]

# authoring leftovers anywhere under assets/ (the loaded art is png/lua/ogg/
# mp3/bin/json; notes and scripts beside it are not)
ASSET_SUFFIXES = (".py", ".ps1", ".psd", ".blend", ".glb", ".kra", ".xcf")
ASSET_NOTES = ("README.md", "prompts.txt", "NOTES.md")

# always shipped, wherever they sit
KEEP_NAMES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "CREDITS.md",
              "THIRD-PARTY-NOTICES.md")

HEADER = """\
# GENERATED by tools/gen_modkitignore.py -- edit the rules there, not here.
#
# gen1recomp's modkit matches this file literally: one exact relative file
# path per line, no globs, no folders. The generator expands its folder
# rules (tests/, tools/, compat/, concepts/, publish/, publish-zip/,
# assets/docs/, assets/ground/source/), the developer docs at the root and
# authoring leftovers under assets/ into the list below. LICENSE and CREDITS
# files always ship.
#
# Regenerate after adding files:   python tools/gen_modkitignore.py
"""


def ignored(path):
    name = path.rsplit("/", 1)[-1]
    if any(path.startswith(f) for f in FOLDERS):
        return True
    if name in KEEP_NAMES:
        return False
    if path in FILES:
        return True
    if path.startswith("assets/") and (path.endswith(ASSET_SUFFIXES)
                                       or name in ASSET_NOTES):
        return True
    return False


# modkit's own walk (gen1recomp tools/modkit.py): it packs what is ON DISK,
# skipping these folders and dot-files. Mirrored here because the install is
# this checkout (mods/TERRARIUM is a junction to it), and a file git ignores
# -- the optional sprite packs under assets/mons and assets/roamers, cut X/Y
# art, scratch output -- would otherwise be packed.
SKIP_DIRS = {".git", ".modkit", "__pycache__", ".vscode"}


def on_disk():
    out = []
    for path in REPO.rglob("*"):
        rel = path.relative_to(REPO)
        parts = rel.parts
        if any(p in SKIP_DIRS or p.startswith(".") for p in parts[:-1]):
            continue
        if path.is_dir():
            continue
        if parts[-1].startswith(".") and parts[-1] != ".luarc.json":
            continue
        out.append(rel.as_posix())
    return out


def build():
    tracked = set(subprocess.run(["git", "ls-files"], cwd=REPO,
                                 capture_output=True, text=True,
                                 check=True).stdout.splitlines())
    disk = on_disk()
    dev = sorted(p for p in disk if p in tracked and ignored(p))
    local = sorted(p for p in disk if p not in tracked)
    out = [HEADER]
    group = None
    for path in dev:
        top = path.split("/", 1)[0] if "/" in path else "(root)"
        if top != group:
            group = top
            out.append(f"\n# {top}")
        out.append(path)
    if local:
        out.append("\n# On THIS machine and not tracked by git (local sprite packs, cut")
        out.append("# third-party art, scratch output): listed so a pack built from this")
        out.append("# checkout never carries them. Another machine regenerates its own.")
        out.extend(local)
    return "\n".join(out) + "\n"


def main():
    text = build()
    target = REPO / ".modkitignore"
    if "--check" in sys.argv:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(".modkitignore is out of date -- run tools/gen_modkitignore.py")
            sys.exit(1)
        print(".modkitignore is up to date")
        return
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {sum(1 for l in text.splitlines() if l and not l.startswith('#'))} "
          f"entries to .modkitignore")


if __name__ == "__main__":
    main()
